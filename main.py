# 상담원 연결 로그 저장소
# AI가 "상담원 연결이 필요하다"고 판단할 때마다, 무슨 질문이었는지 여기에
# 자동으로 기록돼요. /escalation-logs 주소로 접속하면 모아서 볼 수 있어요.
