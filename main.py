def check_and_strip_escalation(user_message: str, ai_answer: str, user_id: str) -> str:
    """AI 답변 끝에 [ESCALATION] 마커가 있으면: 로그에 기록하고, 마커는
    고객에게 안 보이게 잘라내서 돌려줌."""
    if ai_answer and ESCALATION_MARKER in ai_answer:
        escalation_logs.append({
            "time": time.strftime("%Y-%m-%d %H:%M:%S"),
            "user_id": user_id,
            "question": user_message,
            "answer": ai_answer.replace(ESCALATION_MARKER, "").strip(),
        })
        if len(escalation_logs) > MAX_ESCALATION_LOGS:
            del escalation_logs[0]
        ai_answer = ai_answer.replace(ESCALATION_MARKER, "").strip()
    return ai_answer


def get_history(user_id: str) -> list:
    entry = conversation_store.get(user_id)
    if not entry:
        return []
    if time.time() - entry["updated"] > CONVERSATION_TTL_SECONDS:
        del conversation_store[user_id]
        return []
    return entry["messages"]


def save_history(user_id: str, messages: list):
    trimmed = messages[-(MAX_HISTORY_TURNS * 2):]
    conversation_store[user_id] = {"messages": trimmed, "updated": time.time()}


def is_image_url(text: str) -> bool:
    """카카오는 사용자가 사진을 보내면 utterance 필드에 이미지 CDN 주소를 담아서 보내줘요.
    (일반 텍스트가 아니라 사진 URL이 들어있으면 사진으로 판단)"""
    if not text:
        return False
    t = text.strip().lower()
    return t.startswith("http") and ("kakaocdn" in t or any(
        t.split("?")[0].endswith(ext) for ext in [".jpg", ".jpeg", ".png", ".gif", ".webp"]
    ))


